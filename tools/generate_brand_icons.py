"""Generate the requested ship/Haro icons from native VRAM/palette captures.

Developer-only: requires Pillow. The JP capture is shop state 29 after 120 boot
frames + 400 shop frames. The US capture is difficulty state 17, substate 6.
No ROM, raw capture, selector cache or player settings enter a release.
"""

from pathlib import Path
import argparse
import hashlib
import json
import struct
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
SIZES = (16, 24, 32, 48, 64, 128, 256)


def rgba(color):
    return tuple(((color >> shift) & 31) * 255 // 31 for shift in (0, 5, 10)) + (255,)


def haro_sprite(vram, palette):
    image = Image.new("RGBA", (32, 32))
    for y in range(32):
        for x in range(32):
            offset = 65536 + (882 + (y // 8) * 4 + x // 8) * 32 + (y % 8) * 4 + (x % 8) // 2
            index = (vram[offset] >> (4 * (x & 1))) & 15
            if index:
                image.putpixel((x, y), rgba(palette[256 + 5 * 16 + index]))
    return image.crop(image.getbbox())


def difficulty_ship(vram, palette, io):
    u16 = lambda at: struct.unpack_from("<H", io, at)[0]
    control = u16(8)  # Original difficulty-screen BG0, 8bpp.
    if not control & 128:
        raise ValueError("Expected the original 8bpp difficulty-screen ship background")
    char_base, map_base = ((control >> 2) & 3) * 16384, ((control >> 8) & 31) * 2048
    columns = 64 if control & 16384 else 32
    rows = 64 if control & 32768 else 32
    scroll_x, scroll_y = u16(16) & 511, u16(18) & 511
    image = Image.new("RGBA", (240, 160))
    for y in range(160):
        for x in range(240):
            tx, ty = ((x + scroll_x) // 8) % columns, ((y + scroll_y) // 8) % rows
            offset = (
                map_base
                + ((ty // 32) * (columns // 32) + tx // 32) * 2048
                + ((ty % 32) * 32 + tx % 32) * 2
            )
            tile = struct.unpack_from("<H", vram, offset)[0]
            px, py = (x + scroll_x) % 8, (y + scroll_y) % 8
            if tile & 1024:
                px = 7 - px
            if tile & 2048:
                py = 7 - py
            index = vram[char_base + (tile & 1023) * 64 + py * 8 + px]
            if index:
                image.putpixel((x, y), rgba(palette[index]))
    return image.crop(image.getbbox())


def icon(destination, name, source):
    frames = []
    for size in SIZES:
        ratio = size / max(source.size)
        width, height = max(1, round(source.width * ratio)), max(1, round(source.height * ratio))
        frame = Image.new("RGBA", (size, size))
        frame.alpha_composite(
            source.resize((width, height), Image.Resampling.NEAREST),
            ((size - width) // 2, (size - height) // 2),
        )
        frames.append(frame)
    frames[-1].save(
        destination / name,
        format="ICO",
        sizes=[f.size for f in frames],
        append_images=frames[:-1],
        bitmap_format="bmp",
    )
    return frames[2]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    for key in ("jp-vram", "jp-palette", "us-vram", "us-palette", "us-io"):
        parser.add_argument("--" + key, required=True, type=Path)
    args = parser.parse_args()
    haro = haro_sprite(
        args.jp_vram.read_bytes(), struct.unpack("<512H", args.jp_palette.read_bytes())
    )
    ship = difficulty_ship(
        args.us_vram.read_bytes(),
        struct.unpack("<512H", args.us_palette.read_bytes()),
        args.us_io.read_bytes(),
    )
    destination = ROOT / "resources/branding"
    destination.mkdir(parents=True, exist_ok=True)
    game = icon(destination, "Haro.ico", haro)
    launcher = icon(destination, "LauncherShip.ico", ship)
    header = [
        "// Original JP Haro game icon and US difficulty ship launcher icon.",
        "// Generated by tools/generate_brand_icons.py from the approved original ICOs.",
        "#pragma once",
        "#include <array>",
        "#include <cstdint>",
        "namespace seed {",
    ]
    for prefix, frame in (("Brand", game), ("Launcher", launcher)):
        colors = list(frame.tobytes())
        header += [
            f"inline constexpr unsigned k{prefix}WindowIconSize = 32;",
            f"inline constexpr std::array<std::uint8_t, 32 * 32 * 4> k{prefix}WindowIconRgba{{",
        ]
        header += [
            "    " + ", ".join(map(str, colors[n : n + 32])) + ","
            for n in range(0, len(colors), 32)
        ]
        header += ["};"]
    header += ["} // namespace seed", ""]
    (ROOT / "src/brand_window_icon.h").write_text("\n".join(header), encoding="utf-8")
    icons = {
        name: hashlib.sha256((destination / name).read_bytes()).hexdigest()
        for name in ("Haro.ico", "LauncherShip.ico")
    }
    registry = {
        "schema": 1,
        "icons": icons,
        "source": {
            "haro": "JP shop state 29, OBJ tile 882, palette 5, 32x32 sprite",
            "launcher_ship": "US difficulty state 17/substate 6, original transparent BG0, 8bpp",
        },
        "palette": "Original GBA RGB5 colors; nearest-neighbor icon sizes",
    }
    (ROOT / "config/brand-icons.json").write_text(
        json.dumps(registry, indent=2) + "\n", encoding="utf-8"
    )
    print(
        json.dumps({"icons": icons, "native_ship_size": ship.size, "native_haro_size": haro.size})
    )


if __name__ == "__main__":
    main()
