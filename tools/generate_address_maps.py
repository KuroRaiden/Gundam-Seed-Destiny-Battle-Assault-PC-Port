"""Generate named C++/Python address constants and a readable address reference.

Edit analysis/address-map.json, then run this script. --check verifies generated
files without changing them. Raw addresses belong in the registry, not hooks.
"""

import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]


def cpp_name(name):
    return "k" + "".join(part.capitalize() for part in name.split("_"))


def outputs():
    registry = json.loads((ROOT / "analysis/address-map.json").read_text(encoding="utf-8"))
    entries = registry["entries"]
    seen = set()
    for item in entries:
        key = (item["group"], item["name"])
        if key in seen:
            raise ValueError(f"Duplicate symbol: {key}")
        seen.add(key)
        if item["group"] not in ("common", "us", "jp") or not re.fullmatch(
            "[a-z][a-z0-9_]*", item["name"]
        ):
            raise ValueError("Invalid symbol")
        number = int(item["value"], 0)
        if not 0 <= number <= 0xFFFFFFFF:
            raise ValueError("Address is not a 32-bit GBA value")
    header = [
        "// Generated by tools/generate_address_maps.py. Edit analysis/address-map.json.",
        "#pragma once",
        "#include <cstdint>",
        "",
        "namespace seed::address {",
    ]
    python = [
        '"""Generated named GBA addresses. Edit analysis/address-map.json, then regenerate."""',
        "",
    ]
    markdown = [
        "# Named address reference",
        "",
        "Generated from `analysis/address-map.json`. US and JP layouts are independent.",
        "Names describe verified use; unidentified original option meanings are stated explicitly.",
        "Hardware ranges and private test sentinels are distinguished from original game symbols.",
        "The C++ API is in `src/game_addresses.h`; Python tools import `tools/game_addresses.py`.",
        "",
    ]
    for group in ("common", "us", "jp"):
        items = [x for x in entries if x["group"] == group]
        header.append(f"namespace {group} {{")
        python.extend(
            [
                f"class {group.capitalize()}:",
                f'    """{group.upper()} addresses and layout constants."""',
            ]
        )
        markdown.extend(
            [
                f"## {group.upper()}",
                "",
                "| Symbol | Value | Meaning | Evidence |",
                "| --- | --- | --- | --- |",
            ]
        )
        for item in items:
            number = int(item["value"], 0)
            literal = f"0x{number:08X}" if item["kind"] == "address" else str(number)
            header.extend(
                [
                    f'// {item["meaning"]}',
                    f'inline constexpr std::uint32_t {cpp_name(item["name"])} = {literal};',
                ]
            )
            python.append(f'    {item["name"].upper()} = {literal}')
            markdown.append(
                f'| `{group}::{cpp_name(item["name"])}` | `{literal}` | {item["meaning"]} | {item["evidence"]} |'
            )
        header.extend([f"}} // namespace {group}", ""])
        python.append("")
        markdown.append("")
    header.append("} // namespace seed::address")
    return {
        ROOT / "src/game_addresses.h": "\n".join(header).rstrip() + "\n",
        ROOT / "tools/game_addresses.py": "\n".join(python).rstrip() + "\n",
        ROOT / "docs/Address-Map.md": "\n".join(markdown).rstrip() + "\n",
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, text in outputs().items():
        if args.check:
            if not path.is_file() or path.read_text(encoding="utf-8") != text:
                raise SystemExit(f"Out-of-date address map: {path.name}")
        else:
            path.write_text(text, encoding="utf-8")
    print("Named address maps are up to date.")


if __name__ == "__main__":
    main()
